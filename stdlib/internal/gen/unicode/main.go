// Command unicode writes runtime/unicode_tables.h from the Unicode
// Character Database: what String needs to count Characters and to
// compare by canonical equivalence the way Swift does.
//
//	go run ./internal/gen/unicode -ucd DIR
//
// DIR holds the UCD files of the version below; any that are missing
// are downloaded into it first. The version is Swift's: String.count
// and == must agree with swiftc's programs, and they agree only if both
// read the same tables.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const version = "17.0.0"

var files = map[string]string{
	"GraphemeBreakProperty.txt":     "auxiliary/GraphemeBreakProperty.txt",
	"emoji-data.txt":                "emoji/emoji-data.txt",
	"DerivedCoreProperties.txt":     "DerivedCoreProperties.txt",
	"UnicodeData.txt":               "UnicodeData.txt",
	"DerivedNormalizationProps.txt": "DerivedNormalizationProps.txt",
	"SpecialCasing.txt":             "SpecialCasing.txt",
	"PropList.txt":                  "PropList.txt",
	"DerivedNumericType.txt":        "extracted/DerivedNumericType.txt",
	"DerivedNumericValues.txt":      "extracted/DerivedNumericValues.txt",
}

func main() {
	dir := flag.String("ucd", "", "directory holding (or to receive) the UCD files")
	out := flag.String("o", "runtime/unicode_tables.h", "header to write")
	flag.Parse()
	if *dir == "" {
		fmt.Fprintln(os.Stderr, "unicode: -ucd DIR is required")
		os.Exit(2)
	}
	if err := fetch(*dir); err != nil {
		fail(err)
	}
	var b strings.Builder
	header(&b)
	grapheme(&b, *dir)
	normalization(&b, *dir)
	casing(&b, *dir)
	properties(&b, *dir)
	b.WriteString("} // namespace vertex::ucd\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "unicode:", err)
	os.Exit(1)
}

func fetch(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, path := range files {
		dest := filepath.Join(dir, name)
		if _, err := os.Stat(dest); err == nil {
			continue
		}
		url := "https://www.unicode.org/Public/" + version + "/ucd/" + path
		resp, err := http.Get(url)
		if err != nil {
			return err
		}
		if resp.StatusCode != http.StatusOK {
			resp.Body.Close()
			return fmt.Errorf("%s: %s", url, resp.Status)
		}
		f, err := os.Create(dest)
		if err != nil {
			resp.Body.Close()
			return err
		}
		_, err = io.Copy(f, resp.Body)
		resp.Body.Close()
		f.Close()
		if err != nil {
			return err
		}
	}
	return nil
}

func header(b *strings.Builder) {
	fmt.Fprintf(b, `// Code generated by internal/gen/unicode from UCD %s. DO NOT EDIT.
//
// Each range table is a flat array of pairs: the first code point of a
// range, then its last code point shifted left eight with the value in
// the low byte. Searched by bisection on the first of each pair.
#pragma once

#include "vertex/abi.h"

namespace vertex::ucd {

`, version)
}

// A field-separated UCD line: the code point or range, then the rest.
type record struct {
	lo, hi rune
	fields []string
}

func read(dir, name string) []record {
	f, err := os.Open(filepath.Join(dir, name))
	if err != nil {
		fail(err)
	}
	defer f.Close()
	var out []record
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		parts := strings.Split(line, ";")
		for i := range parts {
			parts[i] = strings.TrimSpace(parts[i])
		}
		lo, hi := parseRange(parts[0])
		out = append(out, record{lo, hi, parts[1:]})
	}
	if err := sc.Err(); err != nil {
		fail(err)
	}
	return out
}

func parseRange(s string) (rune, rune) {
	lo, hi, found := strings.Cut(s, "..")
	a := parseHex(lo)
	if !found {
		return a, a
	}
	return a, parseHex(hi)
}

func parseHex(s string) rune {
	n, err := strconv.ParseUint(strings.TrimSpace(s), 16, 32)
	if err != nil {
		fail(fmt.Errorf("bad code point %q", s))
	}
	return rune(n)
}

// The grapheme property byte: Grapheme_Cluster_Break in the low four
// bits, Extended_Pictographic in bit 4, Indic_Conjunct_Break in bits 5-6.
// unicode.h reads the same numbers.
var gcbValues = map[string]byte{
	"CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5, "Regional_Indicator": 6,
	"Prepend": 7, "SpacingMark": 8, "L": 9, "V": 10, "T": 11, "LV": 12, "LVT": 13,
}

var incbValues = map[string]byte{"Consonant": 1, "Extend": 2, "Linker": 3}

func grapheme(b *strings.Builder, dir string) {
	props := map[rune]byte{}
	for _, r := range read(dir, "GraphemeBreakProperty.txt") {
		v, ok := gcbValues[r.fields[0]]
		if !ok {
			fail(fmt.Errorf("unknown Grapheme_Cluster_Break %q", r.fields[0]))
		}
		for c := r.lo; c <= r.hi; c++ {
			props[c] |= v
		}
	}
	for _, r := range read(dir, "emoji-data.txt") {
		if r.fields[0] != "Extended_Pictographic" {
			continue
		}
		for c := r.lo; c <= r.hi; c++ {
			props[c] |= 1 << 4
		}
	}
	for _, r := range read(dir, "DerivedCoreProperties.txt") {
		if r.fields[0] != "InCB" {
			continue
		}
		v, ok := incbValues[r.fields[1]]
		if !ok {
			fail(fmt.Errorf("unknown InCB %q", r.fields[1]))
		}
		for c := r.lo; c <= r.hi; c++ {
			props[c] |= v << 5
		}
	}
	ranges(b, "graphemeProperties", props)
}

func normalization(b *strings.Builder, dir string) {
	ccc := map[rune]byte{}
	decomp := map[rune][]rune{}
	for _, r := range read(dir, "UnicodeData.txt") {
		// Fields: name, category, combining class, bidi, decomposition...
		if n, _ := strconv.Atoi(r.fields[2]); n != 0 {
			ccc[r.lo] = byte(n)
		}
		d := r.fields[4]
		if d == "" || strings.HasPrefix(d, "<") {
			continue // no mapping, or a compatibility one
		}
		var seq []rune
		for _, h := range strings.Fields(d) {
			seq = append(seq, parseHex(h))
		}
		decomp[r.lo] = seq
	}
	excluded := map[rune]bool{}
	for _, r := range read(dir, "DerivedNormalizationProps.txt") {
		if r.fields[0] != "Full_Composition_Exclusion" {
			continue
		}
		for c := r.lo; c <= r.hi; c++ {
			excluded[c] = true
		}
	}
	ranges(b, "combiningClasses", ccc)

	// Full canonical decompositions, expanded to fixpoint.
	var full func(rune) []rune
	full = func(c rune) []rune {
		seq, ok := decomp[c]
		if !ok {
			return []rune{c}
		}
		var out []rune
		for _, x := range seq {
			out = append(out, full(x)...)
		}
		return out
	}
	keys := make([]rune, 0, len(decomp))
	for c := range decomp {
		keys = append(keys, c)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	var index, pool []uint32
	for _, c := range keys {
		seq := full(c)
		if len(seq) > 255 {
			fail(fmt.Errorf("decomposition of %X too long", c))
		}
		index = append(index, uint32(c), uint32(len(pool))<<8|uint32(len(seq)))
		for _, x := range seq {
			pool = append(pool, uint32(x))
		}
	}
	array(b, "decompositionIndex", index)
	array(b, "decompositionPool", pool)

	// Primary composites: two-scalar canonical mappings not excluded.
	type pair struct {
		key uint64
		to  rune
	}
	var pairs []pair
	for _, c := range keys {
		seq := decomp[c]
		if len(seq) != 2 || excluded[c] {
			continue
		}
		pairs = append(pairs, pair{uint64(seq[0])<<32 | uint64(seq[1]), c})
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].key < pairs[j].key })
	var comp []uint32
	for _, p := range pairs {
		comp = append(comp, uint32(p.key>>32), uint32(p.key), uint32(p.to))
	}
	array(b, "compositions", comp)
}

// casing writes each scalar's full uppercase and lowercase mapping where
// it is not the scalar itself: SpecialCasing's unconditional mappings (ß
// uppercases to SS), and UnicodeData's simple ones otherwise. Swift's
// uppercased() and lowercased() map scalar by scalar, without context,
// and so do these. Each table is sorted pairs: the scalar, then the offset
// of its mapping in casePool shifted left eight with its length below.
func casing(b *strings.Builder, dir string) {
	upper, lower := map[rune][]rune{}, map[rune][]rune{}
	for _, r := range read(dir, "UnicodeData.txt") {
		// Fields after the code point: ..., 11 uppercase, 12 lowercase.
		if len(r.fields) > 12 {
			if u := r.fields[11]; u != "" {
				upper[r.lo] = []rune{parseHex(u)}
			}
			if l := r.fields[12]; l != "" {
				lower[r.lo] = []rune{parseHex(l)}
			}
		}
	}
	for _, r := range read(dir, "SpecialCasing.txt") {
		// code; lower; title; upper; [condition;] -- only unconditional.
		if len(r.fields) > 3 && r.fields[3] != "" {
			continue
		}
		seq := func(f string) []rune {
			var out []rune
			for _, h := range strings.Fields(f) {
				out = append(out, parseHex(h))
			}
			return out
		}
		lower[r.lo] = seq(r.fields[0])
		upper[r.lo] = seq(r.fields[2])
	}
	var pool []uint32
	table := func(name string, m map[rune][]rune) {
		keys := make([]rune, 0, len(m))
		for c, to := range m {
			if len(to) == 1 && to[0] == c {
				continue
			}
			keys = append(keys, c)
		}
		sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
		var flat []uint32
		for _, c := range keys {
			flat = append(flat, uint32(c), uint32(len(pool))<<8|uint32(len(m[c])))
			for _, x := range m[c] {
				pool = append(pool, uint32(x))
			}
		}
		array(b, name, flat)
	}
	table("uppercaseMappings", upper)
	table("lowercaseMappings", lower)
	array(b, "casePool", pool)
}

// The scalar property flags scalarFlags holds, which unicode.h reads.
const (
	flagAlphabetic = 1 << iota
	flagUppercase
	flagLowercase
	flagCased
	flagWhiteSpace
	flagMath
)

// generalCategories numbers each General_Category in the order Swift's
// Unicode.GeneralCategory lists them; unicode.h reads the same numbers.
var generalCategories = []string{
	"", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No",
	"Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So",
	"Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn",
}

var numericTypes = map[string]byte{"Decimal": 1, "Digit": 2, "Numeric": 3}

// properties writes what Character's properties ask of its first scalar:
// flags, the general category, the numeric type, and the whole numeric
// values, as (scalar, low word, high word) triples.
func properties(b *strings.Builder, dir string) {
	flags := map[rune]byte{}
	set := func(name string, bit byte, file string) {
		for _, r := range read(dir, file) {
			if r.fields[0] != name {
				continue
			}
			for c := r.lo; c <= r.hi; c++ {
				flags[c] |= bit
			}
		}
	}
	set("Alphabetic", flagAlphabetic, "DerivedCoreProperties.txt")
	set("Uppercase", flagUppercase, "DerivedCoreProperties.txt")
	set("Lowercase", flagLowercase, "DerivedCoreProperties.txt")
	set("Cased", flagCased, "DerivedCoreProperties.txt")
	set("Math", flagMath, "DerivedCoreProperties.txt")
	set("White_Space", flagWhiteSpace, "PropList.txt")
	ranges(b, "scalarFlags", flags)

	gcIndex := map[string]byte{}
	for i, name := range generalCategories {
		gcIndex[name] = byte(i)
	}
	gc := map[rune]byte{}
	var first rune = -1
	for _, r := range read(dir, "UnicodeData.txt") {
		v, ok := gcIndex[r.fields[1]]
		if !ok {
			fail(fmt.Errorf("unknown General_Category %q", r.fields[1]))
		}
		// A range is written as its First and Last lines.
		switch {
		case strings.HasSuffix(r.fields[0], ", First>"):
			first = r.lo
			continue
		case strings.HasSuffix(r.fields[0], ", Last>") && first >= 0:
			for c := first; c <= r.lo; c++ {
				gc[c] = v
			}
			first = -1
			continue
		}
		gc[r.lo] = v
	}
	ranges(b, "generalCategoryRanges", gc)

	nt := map[rune]byte{}
	for _, r := range read(dir, "DerivedNumericType.txt") {
		v, ok := numericTypes[r.fields[0]]
		if !ok {
			fail(fmt.Errorf("unknown Numeric_Type %q", r.fields[0]))
		}
		for c := r.lo; c <= r.hi; c++ {
			nt[c] = v
		}
	}
	ranges(b, "numericTypeRanges", nt)

	// DerivedNumericValues: code; decimal value; ; rational value.
	var whole []uint32
	type value struct {
		c rune
		n uint64
	}
	var vals []value
	for _, r := range read(dir, "DerivedNumericValues.txt") {
		rational := r.fields[len(r.fields)-1]
		if strings.Contains(rational, "/") || strings.HasPrefix(rational, "-") {
			continue
		}
		n, err := strconv.ParseUint(rational, 10, 64)
		if err != nil {
			continue
		}
		for c := r.lo; c <= r.hi; c++ {
			vals = append(vals, value{c, n})
		}
	}
	sort.Slice(vals, func(i, j int) bool { return vals[i].c < vals[j].c })
	for _, v := range vals {
		whole = append(whole, uint32(v.c), uint32(v.n), uint32(v.n>>32))
	}
	array(b, "wholeNumbers", whole)
}

// ranges writes a property map as merged ranges of equal value.
func ranges(b *strings.Builder, name string, props map[rune]byte) {
	cps := make([]rune, 0, len(props))
	for c, v := range props {
		if v != 0 {
			cps = append(cps, c)
		}
	}
	sort.Slice(cps, func(i, j int) bool { return cps[i] < cps[j] })
	var flat []uint32
	for i := 0; i < len(cps); {
		lo, v := cps[i], props[cps[i]]
		j := i
		for j+1 < len(cps) && cps[j+1] == cps[j]+1 && props[cps[j+1]] == v {
			j++
		}
		flat = append(flat, uint32(lo), uint32(cps[j])<<8|uint32(v))
		i = j + 1
	}
	array(b, name, flat)
}

func array(b *strings.Builder, name string, vals []uint32) {
	fmt.Fprintf(b, "inline constexpr u32 %sCount = %d;\n", name, len(vals))
	fmt.Fprintf(b, "static const u32 %s[%d] = {", name, len(vals))
	for i, v := range vals {
		if i%8 == 0 {
			b.WriteString("\n ")
		}
		fmt.Fprintf(b, " 0x%X,", v)
	}
	b.WriteString("\n};\n\n")
}
